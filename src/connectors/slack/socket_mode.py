"""
Slack Socket Mode integration for POLIS.
"""

from __future__ import annotations

import logging
import re
import threading
import time
from slack_bolt import App
from slack_bolt.adapter.socket_mode import SocketModeHandler
from datetime import datetime, timezone
from infrastructure.config.settings import get_settings

from connectors.slack.models import (
    SlackEvent,
    SlackUser,
    SlackChannel,
    SlackMessage,
)

from domain.reasoning.value_objects.conversation_context import ConversationContext

from connectors.slack.services import SlackService

from domain.reasoning import (
    Question,
)
from connectors.slack.routing import (
    EventDeduplicator,
    clean_slack_text,
    is_bot_mentioned,
    is_direct_message as is_direct_channel,
)
from domain.reasoning.repositories import (
    ConversationRepository,
)
from engines.slack.services.slack_identity_service import (
    SlackIdentityService,
)
logger = logging.getLogger(__name__)
class SlackSocketMode:
    """
    Slack Socket Mode listener.
    """

    def __init__(
        self,
        slack_service: SlackService,
        reminder_service,
        slack_client,
        calendar_agent=None,
        calendar_worker=None,
        conversation_repository: ConversationRepository | None = None,
    ) -> None:

        self._slack_service = slack_service
        self._reminder_service = reminder_service
        self._slack_client = slack_client
        self._calendar_agent = calendar_agent
        self._calendar_worker = calendar_worker
        self._identity_service = SlackIdentityService()
        self._settings = get_settings()
        self._deduplicator = EventDeduplicator()

        if conversation_repository is not None:
            self._conversation_repository = conversation_repository
        else:
            try:
                from api.dependencies import get_conversation_repository

                self._conversation_repository = get_conversation_repository()
            except Exception:
                self._conversation_repository = None

        self._app = App(
            token=self._settings.slack_bot_token,
        )

        self._register_handlers()

    def _register_handlers(self) -> None:

        @self._app.event("message")
        def handle_message(event, say, logger):

            # ======================================================
            # Ignore messages generated by bots.
            # ======================================================

            if event.get("bot_id"):
                return

            # ======================================================
            # Ignore Slack message subtypes.
            # ======================================================

            if event.get("subtype"):
                return

            user_id = event.get("user")
            channel_id = event.get("channel")
            text = event.get("text", "")
            ts = event.get("ts")
            thread_ts = event.get("thread_ts")

            if not user_id or not channel_id or not ts:
                return

            bot_user_id = self._settings.slack_bot_user_id

            # Ignore messages authored by POLIS itself to prevent self-reply loops.
            if bot_user_id and user_id == bot_user_id:
                return

            # Prevent duplicate processing of retried or multi-subscribed events.
            if self._deduplicator.is_duplicate(channel_id, ts):
                logger.info(
                    "Ignoring duplicate Slack event: channel=%s, ts=%s",
                    channel_id,
                    ts,
                )
                return

            # ======================================================
            # Always ingest the message first.
            #
            # This preserves the existing learning pipeline.
            # ======================================================

            user_name = None
            if self._identity_service is not None:
                try:
                    user_name = self._identity_service.get_display_name(
                        user_id,
                    )
                except Exception:
                    logger.exception(
                        "Failed to resolve Slack user name: %s",
                        user_id,
                    )
                    user_name = None

            slack_event = SlackEvent(
                user=SlackUser(
                    user_id=user_id,
                    username=user_name,
                ),
                channel=SlackChannel(
                    channel_id=channel_id,
                ),
                message=SlackMessage(
                    text=text,
                    ts=ts,
                    thread_ts=thread_ts,
                ),
            )

            try:

                saved = self._slack_service.ingest(
                    slack_event,
                )

                logger.info(
                    "POLIS processed Slack message: %s",
                    saved.correlation_id.business_id,
                )

            except Exception:

                logger.exception(
                    "POLIS failed to process Slack message",
                )

                return

            # ======================================================
            # Routing gate: Direct Messages, explicit mentions,
            # and established POLIS conversation threads.
            # ======================================================

            is_direct = is_direct_channel(
                event=event,
                channel_id=channel_id,
            )
            is_polis_question = is_bot_mentioned(
                text=text,
                bot_user_id=bot_user_id,
            )

            is_established_thread = False
            if thread_ts and self._conversation_repository is not None:
                existing_context = self._conversation_repository.get(
                    channel_id=channel_id,
                    thread_ts=thread_ts,
                )
                if (
                    existing_context is not None
                    and any(msg.get("role") == "assistant" for msg in existing_context.history)
                ):
                    is_established_thread = True

            if not (is_direct or is_polis_question or is_established_thread):
                return

            question_text = clean_slack_text(
                text=text,
                bot_user_id=bot_user_id,
            )

            if not question_text:
                return

            # ======================================================
            # Stop all active reminders for the requesting user.
            # ======================================================

            if question_text.lower() == "stop":
                stopped_count = self._reminder_service.stop_for_target(
                    user_id,
                )

                reply_text = (
                    f"Stopped {stopped_count} active reminder(s)."
                )
                reply_thread_ts = thread_ts or ts
                self._record_conversation_exchange(
                    channel_id=channel_id,
                    thread_ts=reply_thread_ts,
                    user_id=user_id,
                    user_message=question_text,
                    assistant_message=reply_text,
                )
                say(
                    text=reply_text,
                    thread_ts=reply_thread_ts,
                )
                return

            # ======================================================
            # Detect explicit reminder commands.
            # ======================================================

            reminder_match = re.match(
                r"^remind\s+(.+?)\s+to\s+(.+)$",
                question_text,
                re.IGNORECASE,
            )

            if reminder_match:
                target_text = reminder_match.group(1).strip()
                task = reminder_match.group(2).strip()
                if target_text.startswith("<@"):
                    mention_match = re.fullmatch(
                        r"<@([A-Z0-9]+)(?:\|[^>]+)?>",
                        target_text,
                    )

                    target_user = None

                    if mention_match:
                        target_user = {
                            "id": mention_match.group(1),
                        }
                else:
                    target_user = self._identity_service.resolve_user(
                        target_text,
                    )

                if target_user is None:
                    say(
                        text=(
                            f"I couldn't unambiguously identify "
                            f"the reminder target '{target_text}'."
                        ),
                        thread_ts=thread_ts or ts,
                    )
                    return

                target_user_id = target_user["id"]
                logger.info(
                    "Reminder command detected: target=%s task=%s",
                    target_text,
                    task,
                )
                reminder = self._reminder_service.create(
                    target_user_id=target_user_id,
                    creator_user_id=user_id,
                    task=task,
                    channel_id=channel_id,
                    source_message_ts=ts,
                    source_thread_ts=thread_ts,
                    timezone_name=self._settings.reminder_timezone,
                    time_1=self._settings.reminder_time_1,
                    time_2=self._settings.reminder_time_2,
                )

                reply_text = (
                    f"Done! I've set a reminder. "
                    f"I'll remind <@{target_user_id}> "
                    f"twice daily about: {reminder.task}"
                )
                reply_thread_ts = thread_ts or ts
                self._record_conversation_exchange(
                    channel_id=channel_id,
                    thread_ts=reply_thread_ts,
                    user_id=user_id,
                    user_message=question_text,
                    assistant_message=reply_text,
                )
                say(
                    text=reply_text,
                    thread_ts=reply_thread_ts,
                )
                return

            # ======================================================
            # Detect Calendar Agent commands and interactions.
            # ======================================================

            if self._calendar_agent is not None:
                calendar_response = self._calendar_agent.handle_message(
                    question_text,
                    user_id=user_id,
                    channel_id=channel_id,
                )
                if calendar_response is not None:
                    reply_thread_ts = thread_ts or ts
                    self._record_conversation_exchange(
                        channel_id=channel_id,
                        thread_ts=reply_thread_ts,
                        user_id=user_id,
                        user_message=question_text,
                        assistant_message=calendar_response,
                    )
                    say(
                        text=calendar_response,
                        thread_ts=reply_thread_ts,
                    )
                    return

            # ======================================================
            # Ask the POLIS cognitive engine.
            # ======================================================

            try:
                reply_thread_ts = (
                    thread_ts or ts
                )

                conversation_context = None
                if self._conversation_repository is not None:
                    conversation_context = self._conversation_repository.get(
                        channel_id=channel_id,
                        thread_ts=reply_thread_ts,
                    )

                    is_dm = channel_id.startswith("D")
                    if conversation_context is None:
                        history = []
                        if (
                            is_dm
                            and hasattr(self._conversation_repository, "get_latest")
                        ):
                            latest_context = self._conversation_repository.get_latest(
                                channel_id,
                                user_id=user_id,
                            )
                            if latest_context is not None:
                                history = latest_context.history

                        conversation_context = ConversationContext(
                            user_id=user_id,
                            channel_id=channel_id,
                            thread_ts=reply_thread_ts,
                            history=history,
                            channel_type="im" if is_dm else None,
                        )
                    else:
                        if is_dm and conversation_context.user_id and conversation_context.user_id != user_id:
                            conversation_context = ConversationContext(
                                user_id=user_id,
                                channel_id=channel_id,
                                thread_ts=reply_thread_ts,
                                history=[],
                                channel_type="im",
                            )
                        else:
                            conversation_context = ConversationContext(
                                user_id=user_id,
                                channel_id=channel_id,
                                thread_ts=reply_thread_ts,
                                history=conversation_context.history,
                                channel_type=conversation_context.channel_type or ("im" if is_dm else None),
                            )
                else:
                    conversation_context = ConversationContext(
                        user_id=user_id,
                        channel_id=channel_id,
                        thread_ts=reply_thread_ts,
                    )

                question = Question(
                    text=question_text,
                    context=conversation_context,
                )

                answer = self._slack_service.ask(
                    question,
                )

                logger.info(
                    "POLIS answer confidence: %s",
                    answer.confidence,
                )

                self._record_conversation_exchange(
                    channel_id=channel_id,
                    thread_ts=reply_thread_ts,
                    user_id=user_id,
                    user_message=question_text,
                    assistant_message=answer.text,
                )

                say(
                    text=answer.text,
                    thread_ts=reply_thread_ts,
                )

            except Exception:

                logger.exception(
                    "POLIS failed to answer Slack question",
                )

                say(
                    text=(
                        "I encountered an error while trying "
                        "to answer that question."
                    ),
                    thread_ts=thread_ts or ts,
                )

    def _record_conversation_exchange(
        self,
        channel_id: str,
        thread_ts: str,
        user_id: str,
        user_message: str,
        assistant_message: str,
    ) -> None:
        """
        Record a conversation exchange in the repository to establish thread state.
        """
        if self._conversation_repository is None:
            return

        try:
            context = self._conversation_repository.get(
                channel_id=channel_id,
                thread_ts=thread_ts,
            )

            is_dm = channel_id.startswith("D")
            if context is None:
                context = ConversationContext(
                    user_id=user_id,
                    channel_id=channel_id,
                    thread_ts=thread_ts,
                    channel_type="im" if is_dm else None,
                )
            else:
                if is_dm and context.user_id and context.user_id != user_id:
                    logger.warning(
                        "Cannot record exchange in private DM owned by another user: expected %s, got %s",
                        context.user_id,
                        user_id,
                    )
                    return

                context = ConversationContext(
                    user_id=context.user_id if is_dm else user_id,
                    channel_id=channel_id,
                    thread_ts=thread_ts,
                    history=context.history,
                    channel_type=context.channel_type or ("im" if is_dm else None),
                )

            updated = context.add_exchange(
                user_message=user_message,
                assistant_message=assistant_message,
                user_id=user_id,
            )
            self._conversation_repository.save(updated)

        except Exception:
            logger.exception(
                "Failed to record conversation exchange for thread %s",
                thread_ts,
            )


    def _run_reminder_worker(self) -> None:
        """
        Poll PostgreSQL for due reminders and deliver them via Slack DM.
        """

        while True:
            try:
                due_reminders = self._reminder_service.find_due()

                for reminder in due_reminders:
                    try:
                        dm_channel = self._slack_client.open_dm(
                            reminder.target_user_id,
                        )

                        self._slack_client.post_message(
                            channel=dm_channel,
                            text=(
                                f"Reminder: {reminder.task}\n"
                                "Reply `@POLIS stop` to stop future reminders."
                            ),
                        )

                        sent_at = datetime.now(timezone.utc)

                        next_reminder_at = self._reminder_service.next_reminder_time(
                            now=sent_at,
                            timezone_name=self._settings.reminder_timezone,
                            time_1=self._settings.reminder_time_1,
                            time_2=self._settings.reminder_time_2,
                        )

                        self._reminder_service.mark_sent(
                            reminder,
                            last_sent_at=sent_at,
                            next_reminder_at=next_reminder_at,
                        )

                    except Exception:
                        logger.exception(
                            "Failed to deliver reminder %s",
                            reminder.graph_id,
                        )

            except Exception:
                logger.exception(
                    "Reminder worker iteration failed",
                )

            time.sleep(30)

    def start(self) -> None:
        reminder_worker = threading.Thread(
            target=self._run_reminder_worker,
            name="polis-reminder-worker",
            daemon=True,
        )
        reminder_worker.start()

        if self._calendar_worker is not None:
            self._calendar_worker.start()

        handler = SocketModeHandler(
            self._app,
            self._settings.slack_app_token,
        )
        handler.start()

if __name__ == "__main__":
    from slack_listener import create_listener

    listener = create_listener()
    listener.start()
